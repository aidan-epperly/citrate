"""Generate the matrix product kernels templates/kernels/gemm_real.luau.in and gemm_complex.luau.in.

The kernels compute C := alpha R Q + beta C for column-major C (m by n), where R holds the
rows of the left factor (row i at R[i * p .. i * p + p - 1]) and Q the columns of the
right factor (column j at Q[j * p ..]), so both are contiguous along the inner index k.
Register blocking: each block of C keeps its sums in locals over k, so every element read
from R or Q feeds several multiply-adds. The cost per multiply-add is mostly the buffer
reads, (mr + nr) / (mr nr) of them, so blocks are as large as Luau's limit of 200 locals
per function allows; rows and columns left over go to 4 by 4 blocks and then to single
entries. Sums run in double precision and each entry of C is rounded once.

Block shapes (measured, bench/matmul.luau): real 8 by 16, the largest within the locals
limit (12 by 12 does not compile; 8 by 8 is 20% slower, 4 by 4 50%); complex 8 by 8,
where the four real multiply-adds per complex one leave arithmetic, not reads, the cost,
so shapes from 4 by 4 to 6 by 6 come within 10%.

Usage: python tools/gen_kernels.py (generate.py runs it).
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

HEADER = """-- Matrix product kernels (generated by tools/gen_kernels.py; do not edit).
--
-- gemm_kernel(R, Q, c, m, p, n, alpha, beta): C := alpha R Q + beta C for column-major C
-- (m by n, in the buffer c), with the rows of R and the columns of Q (both p long) stored
-- contiguously: R[i, k] at element i * p + k and Q[k, j] at element j * p + k. beta = 0
-- does not read C. Register-blocked ({big} blocks, then 4 by 4, then single entries); sums
-- in double precision.
"""


def real_block(name, mr, nr):
    L = []
    L.append(f"\tlocal function {name}(R: buffer, Q: buffer, c: buffer, m: number, p: number, i0: number, i1: number, j0: number, j1: number, alpha: number, beta: number)")
    L.append(f"\t\tfor j = j0, j1 - {nr}, {nr} do")
    L.append("\t\t\t" + "; ".join(f"local q{s} = @W@ * (j + {s}) * p" for s in range(nr)))
    L.append(f"\t\t\tfor i = i0, i1 - {mr}, {mr} do")
    L.append("\t\t\t\t" + "; ".join(f"local r{t} = @W@ * (i + {t}) * p" for t in range(mr)))
    for t in range(mr):
        L.append("\t\t\t\t" + "local " + ", ".join(f"s{t}_{s}" for s in range(nr)) + " = " + ", ".join("0" for _ in range(nr)))
    L.append("\t\t\t\tfor k = 0, @W@ * (p - 1), @W@ do")
    L.append("\t\t\t\t\t" + "; ".join(f"local x{t} = @READ@(R, r{t} + k)" for t in range(mr)))
    L.append("\t\t\t\t\t" + "; ".join(f"local y{s} = @READ@(Q, q{s} + k)" for s in range(nr)))
    for t in range(mr):
        L.append("\t\t\t\t\t" + "; ".join(f"s{t}_{s} += x{t} * y{s}" for s in range(nr)))
    L.append("\t\t\t\tend")
    for s in range(nr):
        L.append(f"\t\t\t\tlocal o{s} = @W@ * ((j + {s}) * m + i)")
    L.append("\t\t\t\tif beta == 0 then")
    for s in range(nr):
        L.append("\t\t\t\t\t" + "; ".join(f"@WRITE@(c, o{s} + {('@W@ * ' + str(t)) if t else '0'}, alpha * s{t}_{s})" for t in range(mr)))
    L.append("\t\t\t\telse")
    for s in range(nr):
        for t in range(mr):
            off = f"o{s} + @W@ * {t}" if t else f"o{s}"
            L.append(f"\t\t\t\t\t@WRITE@(c, {off}, alpha * s{t}_{s} + beta * @READ@(c, {off}))")
    L.append("\t\t\t\tend")
    L.append("\t\t\tend")
    L.append("\t\tend")
    L.append("\tend")
    return "\n".join(L)


def complex_block(name, mr, nr):
    L = []
    L.append(f"\tlocal function {name}(R: buffer, Q: buffer, c: buffer, m: number, p: number, i0: number, i1: number, j0: number, j1: number, alpha: number, beta: number)")
    L.append(f"\t\tfor j = j0, j1 - {nr}, {nr} do")
    L.append("\t\t\t" + "; ".join(f"local q{s} = @E@ * (j + {s}) * p" for s in range(nr)))
    L.append(f"\t\t\tfor i = i0, i1 - {mr}, {mr} do")
    L.append("\t\t\t\t" + "; ".join(f"local r{t} = @E@ * (i + {t}) * p" for t in range(mr)))
    for t in range(mr):
        L.append("\t\t\t\t" + "local " + ", ".join(f"u{t}_{s}, v{t}_{s}" for s in range(nr)) + " = " + ", ".join("0, 0" for _ in range(nr)))
    L.append("\t\t\t\tfor k = 0, @E@ * (p - 1), @E@ do")
    L.append("\t\t\t\t\t" + "; ".join(f"local a{t}, b{t} = @READ@(R, r{t} + k), @READ@(R, r{t} + k + @W@)" for t in range(mr)))
    L.append("\t\t\t\t\t" + "; ".join(f"local c{s}, d{s} = @READ@(Q, q{s} + k), @READ@(Q, q{s} + k + @W@)" for s in range(nr)))
    for t in range(mr):
        L.append("\t\t\t\t\t" + "; ".join(f"u{t}_{s} += a{t} * c{s} - b{t} * d{s}; v{t}_{s} += a{t} * d{s} + b{t} * c{s}" for s in range(nr)))
    L.append("\t\t\t\tend")
    for s in range(nr):
        for t in range(mr):
            off = f"@E@ * ((j + {s}) * m + i + {t})"
            L.append(f"\t\t\t\tdo")
            L.append(f"\t\t\t\t\tlocal o = {off}")
            L.append(f"\t\t\t\t\tif beta == 0 then")
            L.append(f"\t\t\t\t\t\t@WRITE@(c, o, alpha * u{t}_{s})")
            L.append(f"\t\t\t\t\t\t@WRITE@(c, o + @W@, alpha * v{t}_{s})")
            L.append(f"\t\t\t\t\telse")
            L.append(f"\t\t\t\t\t\t@WRITE@(c, o, alpha * u{t}_{s} + beta * @READ@(c, o))")
            L.append(f"\t\t\t\t\t\t@WRITE@(c, o + @W@, alpha * v{t}_{s} + beta * @READ@(c, o + @W@))")
            L.append(f"\t\t\t\t\tend")
            L.append(f"\t\t\t\tend")
    L.append("\t\t\tend")
    L.append("\t\tend")
    L.append("\tend")
    return "\n".join(L)


REAL_SINGLE = """	local function single(R: buffer, Q: buffer, c: buffer, m: number, p: number, i0: number, i1: number, j0: number, j1: number, alpha: number, beta: number)
		for j = j0, j1 - 1 do
			for i = i0, i1 - 1 do
				local s = 0
				local r, q = @W@ * i * p, @W@ * j * p
				for k = 0, @W@ * (p - 1), @W@ do
					s += @READ@(R, r + k) * @READ@(Q, q + k)
				end
				local o = @W@ * (j * m + i)
				@WRITE@(c, o, if beta == 0 then alpha * s else alpha * s + beta * @READ@(c, o))
			end
		end
	end"""

COMPLEX_SINGLE = """	local function single(R: buffer, Q: buffer, c: buffer, m: number, p: number, i0: number, i1: number, j0: number, j1: number, alpha: number, beta: number)
		for j = j0, j1 - 1 do
			for i = i0, i1 - 1 do
				local u, v = 0, 0
				local r, q = @E@ * i * p, @E@ * j * p
				for k = 0, @E@ * (p - 1), @E@ do
					local a, b = @READ@(R, r + k), @READ@(R, r + k + @W@)
					local x, y = @READ@(Q, q + k), @READ@(Q, q + k + @W@)
					u += a * x - b * y
					v += a * y + b * x
				end
				local o = @E@ * (j * m + i)
				if beta == 0 then
					@WRITE@(c, o, alpha * u)
					@WRITE@(c, o + @W@, alpha * v)
				else
					@WRITE@(c, o, alpha * u + beta * @READ@(c, o))
					@WRITE@(c, o + @W@, alpha * v + beta * @READ@(c, o + @W@))
				end
			end
		end
	end"""

DRIVER = """	-- Cover rows i0 .. i1 - 1 and columns j0 .. j1 - 1: {mr} by {nr} blocks, then 4 by 4
	-- blocks over what is left, then single entries.
	function gemm_kernel(R: buffer, Q: buffer, c: buffer, m: number, p: number, n: number, alpha: number, beta: number)
		local mb, nb = m - m % {mr}, n - n % {nr}
		big(R, Q, c, m, p, 0, mb, 0, nb, alpha, beta)
		-- The right strip (all rows) and the bottom strip (the big blocks' columns).
		local function rest(i0: number, i1: number, j0: number, j1: number)
			if i1 <= i0 or j1 <= j0 then
				return
			end
			local i4 = i0 + (i1 - i0) - (i1 - i0) % 4
			local j4 = j0 + (j1 - j0) - (j1 - j0) % 4
			small(R, Q, c, m, p, i0, i4, j0, j4, alpha, beta)
			single(R, Q, c, m, p, i4, i1, j0, j4, alpha, beta)
			single(R, Q, c, m, p, i0, i1, j4, j1, alpha, beta)
		end
		rest(0, m, nb, n)
		rest(mb, m, 0, nb)
	end"""


def kernel_file(block, single, mr, nr):
    parts = [HEADER.format(big=f"{mr} by {nr}"), "local gemm_kernel: (R: buffer, Q: buffer, c: buffer, m: number, p: number, n: number, alpha: number, beta: number) -> ()", "do"]
    parts.append(block("big", mr, nr))
    parts.append("")
    parts.append(block("small", 4, 4))
    parts.append("")
    parts.append(single)
    parts.append("")
    parts.append(DRIVER.format(mr=mr, nr=nr))
    parts.append("end")
    return "\n".join(parts) + "\n"


SHAPES = {"real": (8, 16), "complex": (8, 8)}


def outputs() -> dict:
    return {
        "gemm_real.luau.in": kernel_file(real_block, REAL_SINGLE, *SHAPES["real"]),
        "gemm_complex.luau.in": kernel_file(complex_block, COMPLEX_SINGLE, *SHAPES["complex"]),
    }


def main(check: bool = False) -> list:
    stale = []
    for name, text in outputs().items():
        path = ROOT / "templates" / "kernels" / name
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != text:
            stale.append(name)
            if not check:
                path.write_text(text, encoding="utf-8", newline="\n")
    return stale


if __name__ == "__main__":
    import sys

    print(main("--check" in sys.argv[1:]) or "kernels up to date")
