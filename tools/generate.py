"""Generate the array modules in src/ from templates/, and the API reference in docs/.

Each element type (f32, f64, c32, c64) gets its own modules because Luau only turns
`buffer.readf64` and friends into fast calls when they are written out literally; passing
them in as parameters made the kernels 3-10x slower. Each type's functions are split into
parts (array_f64, matrix_f64, gemm_f64, ...; see PARTS), and f64.luau combines them.

Templates:
  templates/real/<part>.luau.in, templates/complex/<part>.luau.in   one per part
  templates/<family>/module.luau.in    the combined module (f64.luau, ...)
  templates/<family>/prelude.luau.in   types and small helpers included in every part
  templates/shared/                    code shared by the real and complex families
  templates/kernels/                   generated by gen_kernels.py and gen_sparse_kernels.py

Parts call each other only for whole operations (an axpy over an array costs the same
called from another module); per-element helpers live in the prelude, copied into each
part, because a call into another module is not inlined and cost 6 times more (14 against
2.3 ns per call for a one-line helper).

Template syntax:
  @W@, @E@, @EPS@, @READ@, @WRITE@, @NAME@, @SCALAR@, @TAG@  substituted per type
  --@f32 / --@f64 / --@c32 / --@c64 <line>   line kept (marker removed) only for that type
  --@vec / --@buf <line>                    (the XPBD core) only for vector or buffer storage
  --@include <path>                         replaced by templates/<path>
  --@unroll                                 the next loop (over k) unrolled by 4
  --@optional                               the next definition dropped if unused
  --@inline                                 the next local function pasted in at each call

Usage: python tools/generate.py [--check]
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# The parts of each element type's module, in dependency order (each may require the ones
# before it), and the element types.
PARTS = ["array", "matrix", "gemm", "factor", "fft", "structured", "sparse", "eigen", "matfun"]

TYPES = [
    ("real", {"NAME": "Single-precision real", "W": "4", "EPS": "2 ^ -24", "CMOD": "c32",
              "READ": "buffer.readf32", "WRITE": "buffer.writef32", "TAG": "f32"}),
    ("real", {"NAME": "Double-precision real", "W": "8", "EPS": "2 ^ -53", "CMOD": "c64",
              "READ": "buffer.readf64", "WRITE": "buffer.writef64", "TAG": "f64"}),
    ("complex", {"NAME": "Single-precision complex", "W": "4", "E": "8", "EPS": "2 ^ -24",
                 "READ": "buffer.readf32", "WRITE": "buffer.writef32",
                 "SCALAR": "vectors (x = re, y = im), as in complex32", "TAG": "c32"}),
    ("complex", {"NAME": "Double-precision complex", "W": "8", "E": "16", "EPS": "2 ^ -53",
                 "READ": "buffer.readf64", "WRITE": "buffer.writef64",
                 "SCALAR": "(re, im) pairs of numbers, as in complex64", "TAG": "c64"}),
]

# (template, output) pairs: each part as <part>_<tag>.luau, and the module that combines
# them as <tag>.luau.
TARGETS = []
for family, subs in TYPES:
    for part in PARTS:
        TARGETS.append((f"{family}/{part}.luau.in", f"{part}_{subs['TAG']}.luau", subs))
    TARGETS.append((f"{family}/module.luau.in", f"{subs['TAG']}.luau", subs))

# The XPBD solver's core, for each way of storing 3D points: buffers of f64 or f32 (x, y, z
# per point) and tables of vectors. xpbd.luau picks one by the caller's representation.
XPBD_STORAGE = [
    {"TAG": "f64", "W": "8", "READ": "buffer.readf64", "WRITE": "buffer.writef64", "STORE": "buffer", "NAME": "f64 buffers"},
    {"TAG": "f32", "W": "4", "READ": "buffer.readf32", "WRITE": "buffer.writef32", "STORE": "buffer", "NAME": "f32 buffers"},
    {"TAG": "vec", "W": "1", "STORE": "{ vector }", "NAME": "vectors"},
]
for subs in XPBD_STORAGE:
    TARGETS.append(("xpbd/xpbd.luau.in", f"xpbd_{subs['TAG']}.luau", subs))

MARKER = re.compile(r"^--@(f32|f64|c32|c64|vec|buf) ?(.*)$")
INCLUDE = re.compile(r"^--@include (\S+)$")
PLACEHOLDER = re.compile(r"@([A-Z]+)@")


def expand_includes(template: str) -> list[str]:
    lines = []
    for line in template.splitlines():
        m = INCLUDE.match(line)
        if m:
            lines.extend(expand_includes((ROOT / "templates" / m.group(1)).read_text(encoding="utf-8")))
        else:
            lines.append(line)
    return lines


UNROLL = re.compile(r"^(\s*)--@unroll$")
LOOP = re.compile(r"^(\s*)for k = (.+), (.+), (\S+) do$")
UNROLL_BY = 4


def unroll(lines: list[str]) -> list[str]:
    """Expands each `--@unroll` marker: the loop `for k = start, stop, step do ... end` on
    the next line becomes a loop doing UNROLL_BY iterations' bodies per pass (each in its
    own do-block, with k offset by multiples of step) and a loop over the remainder. The
    bodies run in the same order, so results are unchanged. Loop overhead dominates short
    loop bodies in Luau: unrolled axpy and dot run 3-4x faster."""
    out = []
    i = 0
    while i < len(lines):
        m = UNROLL.match(lines[i])
        if not m:
            out.append(lines[i])
            i += 1
            continue
        loop = LOOP.match(lines[i + 1])
        assert loop and loop.group(1) == m.group(1), f"--@unroll must precede a loop over k: {lines[i + 1]!r}"
        ind, start, stop, step = loop.groups()
        j = i + 2
        while lines[j] != ind + "end":
            j += 1
        body = lines[i + 2:j]
        out.append(f"{ind}do")
        out.append(f"{ind}\tlocal k_start, k_stop = {start}, {stop}")
        out.append(f"{ind}\tlocal k_split = k_start + ({step}) * (((k_stop - k_start) // ({step}) + 1) // {UNROLL_BY} * {UNROLL_BY})")
        out.append(f"{ind}\tfor k = k_start, k_split - 1, {UNROLL_BY} * ({step}) do")
        for t in range(UNROLL_BY):
            out.append(f"{ind}\t\tdo")
            offset = f"(k + {step} * {t})" if t else "k"
            out += ["\t\t" + re.sub(r"\bk\b", offset, line) for line in body]
            out.append(f"{ind}\t\tend")
        out.append(f"{ind}\tend")
        out.append(f"{ind}\tfor k = k_split, k_stop, {step} do")
        out += ["\t" + line for line in body]
        out.append(f"{ind}\tend")
        out.append(f"{ind}end")
        i = j + 1
    return out


OPTIONAL = "--@optional"


def prune(lines: list[str]) -> list[str]:
    """Drops each `--@optional` definition (a function up to its closing `end`, or a
    one-line local or type alias, with the comments above it) that nothing else in the
    module uses: the prelude's helpers are copied into every part, and most parts need only
    a few."""
    while True:
        blocks = []
        for i, line in enumerate(lines):
            if line != OPTIONAL:
                continue
            j = i + 1
            while lines[j].startswith("--") and not re.match(r"^--@(f32|f64|c32|c64|vec|buf) ", lines[j]):
                j += 1
            body = re.sub(r"^--@\w+ ?", "", lines[j])
            m = re.match(r"^(?:local (?:function )?|type )(\w+)", body)
            assert m, f"--@optional must precede a local or type definition: {lines[j]!r}"
            end = j
            if body.startswith("local function"):
                while re.sub(r"^--@\w+ ?", "", lines[end]) != "end":
                    end += 1
            blocks.append((i, end, m.group(1)))
        drop = None
        for i, end, name in blocks:
            # uses in code: not in comments, not fields (buffer.create), not other locals of
            # the same name
            used = False
            for l in lines[:i] + lines[end + 1:]:
                code = re.sub(r'"[^"]*"', '""', re.sub(r"--.*$", "", l))
                if re.search(rf"(?<![\w.]){name}\b", code) and not re.match(rf"^\s*(local|for)\s+[\w\s,]*\b{name}\b\s*[,=:]", code):
                    used = True
                    break
            if not used:
                drop = (i, end)
                break
        if drop is None:
            return [l for l in lines if l != OPTIONAL]
        lines = lines[: drop[0]] + lines[drop[1] + 1:]


INLINE = "--@inline"
KEYWORDS = set("and break do else elseif end false for function if in local nil not or repeat return then "
               "true until while continue type".split())
GLOBALS = {"buffer", "math", "table", "string", "vector", "bit32", "assert", "error", "select", "type",
           "typeof", "ipairs", "pairs", "tostring", "tonumber", "unpack", "setmetatable", "print"}
IDENT = re.compile(r"(?<![\w.:@])[A-Za-z_]\w*(?![\w@])")
ATOM = re.compile(r"-?[\w.]+")


def mask(line: str) -> str:
    """The line with the insides of string literals and any comment replaced by NULs, so
    that searches see only code; positions are unchanged."""
    out = list(line)
    i, quote = 0, None
    while i < len(line):
        c = line[i]
        if quote:
            if c == "\\":
                out[i : i + 2] = "\0" * len(out[i : i + 2])
                i += 2
                continue
            if c == quote:
                quote = None
            else:
                out[i] = "\0"
        elif c in "\"'`":
            quote = c
        elif line.startswith("--", i):
            out[i:] = "\0" * (len(line) - i)
            break
        i += 1
    return "".join(out)


def close_paren(code: str, start: int) -> int:
    """The index of the bracket closing the one at `start`."""
    depth = 0
    for i in range(start, len(code)):
        if code[i] in "([{":
            depth += 1
        elif code[i] in ")]}":
            depth -= 1
            if depth == 0:
                return i
    raise ValueError(f"unbalanced brackets: {code!r}")


def split_top(text: str) -> list[str]:
    """text split at the commas outside brackets and strings."""
    code = mask(text)
    parts, depth, last = [], 0, 0
    for i, c in enumerate(code):
        if c in "([{":
            depth += 1
        elif c in ")]}":
            depth -= 1
        elif c == "," and depth == 0:
            parts.append(text[last:i].strip())
            last = i + 1
    parts.append(text[last:].strip())
    return [p for p in parts if p]


def atomic(expr: str) -> bool:
    """Whether expr needs no parentheses wherever it is put: a name, number or field, or a
    call or parenthesized expression."""
    code = mask(expr)
    if ATOM.fullmatch(code):
        return True
    m = re.match(r"^[\w.@]*\(", code)
    return bool(m) and close_paren(code, m.end() - 1) == len(code) - 1


def whole(code: str, start: int, end: int) -> bool:
    """Whether code[start:end] is a whole argument, right-hand side or return value."""
    before, after = code[:start].rstrip(), code[end:].lstrip("\0 \t")
    return (before == "" or before[-1] in "(,=" or re.search(r"\breturn$", before) is not None) and (
        after == "" or after[0] in ",)")


def substitute(text: str, values: dict[str, str]) -> str:
    """text with the names in `values` replaced by their values, which are parenthesized
    unless atomic or put as a whole argument."""
    code = mask(text)
    out, last = [], 0
    for m in IDENT.finditer(code):
        if m.group(0) not in values:
            continue
        value = values[m.group(0)]
        if not atomic(value) and not whole(code, m.start(), m.end()):
            value = f"({value})"
        out += [text[last : m.start()], value]
        last = m.end()
    return "".join(out) + text[last:]


def indent_of(line: str) -> int:
    return len(line) - len(line.lstrip("\t"))


def binds(code: str, name: str) -> bool:
    """Whether the line declares `name` (a local, a loop variable or a parameter)."""
    return bool(re.search(rf"^\s*(local|for)\b[^=]*(?<![\w.]){name}\b|\bfunction\b[^)]*[(,]\s*{name}\b", code))


def inline(lines: list[str]) -> list[str]:
    """Expands each `--@inline` function: the definition (with the comments above it) is
    dropped, and each call in its scope is replaced by its body with the arguments put for
    the parameters. A function whose body is `return <expressions>` can be called within
    any expression (if it returns several values, only where all are kept); any other is a
    statement, its body put in a do-block if it declares locals. A body line
    `local p = <parameter>` is dropped where the argument is a name or a number, which is
    then used directly. A local of the same name shadows the function as in Luau; a name
    the body uses from an enclosing routine (n in at(i, j)) must not be rebound where the
    function is used, which is an error.

    Luau inlines small local functions itself, but only native code makes that free.
    Interpreted, as on Roblox clients, the copies into and out of the inlined body cost
    25-65% in an LU update loop; the text expanded here compiles to the same bytecode as
    the loop written out by hand."""
    while True:
        start = next((i for i, l in enumerate(lines) if l.strip() == INLINE), None)
        if start is None:
            return lines
        ind = lines[start][: indent_of(lines[start])]
        d = start + 1
        while lines[d].strip().startswith("--"):
            d += 1
        m = re.match(r"^\s*local function (\w+)\((.*?)\)(?::.*)?$", lines[d])
        assert m, f"--@inline must precede a local function: {lines[d]!r}"
        name = m.group(1)
        params = [p.split(":")[0].strip() for p in m.group(2).split(",") if p.strip()]
        end = d + 1
        while lines[end] != ind + "end":
            end += 1
        body = [l[len(ind) + 1 :] for l in lines[d + 1 : end]]
        expr = body[0][len("return ") :] if len(body) == 1 and body[0].startswith("return ") else None
        declared = {n.split(":")[0].strip() for l in body if l.lstrip().startswith("local ")
                    for n in l.lstrip()[6:].split("=")[0].split(",")}
        code = [re.sub(r":+\s*\w+\??", "", mask(l)) for l in body]  # (type annotations dropped)
        free = {n for c in code for n in IDENT.findall(c)} - set(params) - declared - KEYWORDS - GLOBALS
        stop = end + 1
        while stop < len(lines) and (not ind or lines[stop].strip() == "" or indent_of(lines[stop]) >= len(ind)):
            stop += 1
        out = []
        shadow = None  # while a local of the same name is in scope: the indent it ends below
        for line in lines[end + 1 : stop]:
            code = mask(line)
            if shadow is not None and code.strip() and indent_of(line) < shadow:
                shadow = None
            if shadow is None and binds(code, name):
                # (a local, until its block ends; a loop variable or parameter, until the
                # loop's or function's end)
                inner = re.match(r"^\s*(for\b|.*\bfunction\b[^)]*[(,]\s*" + name + r"\b)", code)
                shadow = indent_of(line) + (1 if inner else 0)
            if shadow is not None:
                out.append(line)
                continue
            for f in free if ind else ():
                if binds(code, f):
                    raise ValueError(f"{name} (--@inline) uses {f}, which is rebound in its scope: {line.strip()!r}")
            pending = [line]
            while pending:
                line = pending.pop(0)
                code = mask(line)
                m = re.search(rf"(?<![\w.:]){name}\b", code)
                if not m:
                    out.append(line)
                    continue
                open_ = m.end()
                assert code[open_ : open_ + 1] == "(", f"{name} (--@inline) must be called directly: {line!r}"
                close = close_paren(code, open_)
                args = split_top(line[open_ + 1 : close])
                assert len(args) == len(params), f"{name} takes {len(params)} arguments: {line!r}"
                values = dict(zip(params, args))
                if expr is not None:
                    text = substitute(expr, values)
                    full = whole(code, m.start(), close + 1)
                    if len(split_top(text)) > 1:
                        assert full and code[close + 1 :].lstrip("\0 \t")[:1] != ",", (
                            f"{name} returns several values, which would be cut to one here: {line!r}"
                        )
                    elif not full and not atomic(text):
                        text = f"({text})"
                    pending.insert(0, line[: m.start()] + text + line[close + 1 :])
                    continue
                assert code.strip("\0 \t") == code[m.start() : close + 1], f"{name} (--@inline) is a statement: {line!r}"
                # The body's locals get a trailing underscore, so they shadow nothing at the
                # call site (which the type checker would flag).
                values.update({n: n + "_" for n in declared})
                kept = []
                for l in body:
                    c = re.match(r"^local (\w+) = (\w+)$", l)
                    if c and c.group(2) in params and ATOM.fullmatch(values[c.group(2)]):
                        values[c.group(1)] = values[c.group(2)]
                    else:
                        kept.append(l)
                lead = line[: indent_of(line)]
                block = any(l.startswith("local ") for l in kept)
                used = {n for a in args for n in IDENT.findall(mask(a))}
                assert not used & {n + "_" for n in declared}, f"{name}: an argument uses a name its body declares: {line!r}"
                expanded = [lead + ("\t" if block else "") + substitute(l, values) for l in kept]
                pending[:0] = [lead + "do", *expanded, lead + "end"] if block else expanded
        lines = lines[:start] + out + lines[stop:]


def render(template: str, subs: dict) -> str:
    lines = []
    for line in expand_includes(template):
        m = MARKER.match(line)
        if m:
            # --@buf: kept for both buffer storages of the XPBD core
            keep = subs.get("STORE") == "buffer" if m.group(1) == "buf" else m.group(1) == subs.get("TAG")
            if not keep:
                continue
            line = m.group(2)
        lines.append(line)
    text = "\n".join(unroll(prune(inline(lines)))) + "\n"
    # (pruning leaves the blank lines around what it dropped)
    text = re.sub(r"\n{3,}", "\n\n", text)

    def sub(m):
        key = m.group(1)
        if key not in subs:
            raise KeyError(f"no value for @{key}@")
        return subs[key]

    return PLACEHOLDER.sub(sub, text)


def main() -> int:
    check = "--check" in sys.argv[1:]
    sys.path.insert(0, str(ROOT / "tools"))
    # No bytecode cache: an edit within the same second as the cache can go unseen.
    sys.dont_write_bytecode = True
    import gen_kernels
    import gen_sparse_kernels
    import gen_docs

    written = gen_kernels.main(check) + gen_sparse_kernels.main(check)
    stale = [f"templates/kernels/{name}" for name in written] if check else []
    for name in [] if check else written:
        print(f"wrote templates/kernels/{name}")
    for template, target, subs in TARGETS:
        text = render((ROOT / "templates" / template).read_text(encoding="utf-8"), subs)
        path = ROOT / "src" / target
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            continue
        if check:
            stale.append(target)
        else:
            path.write_text(text, encoding="utf-8", newline="\n")
            print(f"wrote src/{target}")
    # The API reference, from the doc comments of the generated modules.
    docs = gen_docs.main(check)
    stale += docs if check else []
    for name in [] if check else docs:
        print(f"wrote {name}")
    if stale:
        print("out of date (run python tools/generate.py): " + ", ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
