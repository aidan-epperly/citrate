"""Generate the array modules in src/ from templates/, and the API reference in docs/.

Each element type (f32, f64, c32, c64) gets its own modules because Luau only turns
`buffer.readf64` and friends into fast calls when they are written out literally; passing
them in as parameters made the kernels 3-10x slower. Each type's functions are split into
parts (array_f64, matrix_f64, gemm_f64, ...; see PARTS), and f64.luau combines them.

Templates:
  templates/real/<part>.luau.in, templates/complex/<part>.luau.in   one per part
  templates/<family>/module.luau.in    the combined module (f64.luau, ...)
  templates/<family>/prelude.luau.in   types and small helpers included in every part
  templates/shared/                    code shared by the real and complex families
  templates/kernels/                   generated by gen_kernels.py and gen_sparse_kernels.py

Parts call each other only for whole operations (an axpy over an array costs the same
called from another module); per-element helpers live in the prelude, copied into each
part, because a call into another module is not inlined and cost 6 times more (14 against
2.3 ns per call for a one-line helper).

Template syntax:
  @W@, @E@, @EPS@, @READ@, @WRITE@, @NAME@, @SCALAR@, @TAG@  substituted per type
  --@f32 / --@f64 / --@c32 / --@c64 <line>   line kept (marker removed) only for that type
  --@include <path>                         replaced by templates/<path>
  --@unroll                                 the next loop (over k) unrolled by 4
  --@optional                               the next definition dropped if unused

Usage: python tools/generate.py [--check]
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# The parts of each element type's module, in dependency order (each may require the ones
# before it), and the element types.
PARTS = ["array", "matrix", "gemm", "factor", "fft", "structured", "sparse", "eigen", "matfun"]

TYPES = [
    ("real", {"NAME": "Single-precision real", "W": "4", "EPS": "2 ^ -24", "CMOD": "c32",
              "READ": "buffer.readf32", "WRITE": "buffer.writef32", "TAG": "f32"}),
    ("real", {"NAME": "Double-precision real", "W": "8", "EPS": "2 ^ -53", "CMOD": "c64",
              "READ": "buffer.readf64", "WRITE": "buffer.writef64", "TAG": "f64"}),
    ("complex", {"NAME": "Single-precision complex", "W": "4", "E": "8", "EPS": "2 ^ -24",
                 "READ": "buffer.readf32", "WRITE": "buffer.writef32",
                 "SCALAR": "vectors (x = re, y = im), as in complex32", "TAG": "c32"}),
    ("complex", {"NAME": "Double-precision complex", "W": "8", "E": "16", "EPS": "2 ^ -53",
                 "READ": "buffer.readf64", "WRITE": "buffer.writef64",
                 "SCALAR": "(re, im) pairs of numbers, as in complex64", "TAG": "c64"}),
]

# (template, output) pairs: each part as <part>_<tag>.luau, and the module that combines
# them as <tag>.luau.
TARGETS = []
for family, subs in TYPES:
    for part in PARTS:
        TARGETS.append((f"{family}/{part}.luau.in", f"{part}_{subs['TAG']}.luau", subs))
    TARGETS.append((f"{family}/module.luau.in", f"{subs['TAG']}.luau", subs))

MARKER = re.compile(r"^--@(f32|f64|c32|c64) ?(.*)$")
INCLUDE = re.compile(r"^--@include (\S+)$")
PLACEHOLDER = re.compile(r"@([A-Z]+)@")


def expand_includes(template: str) -> list[str]:
    lines = []
    for line in template.splitlines():
        m = INCLUDE.match(line)
        if m:
            lines.extend(expand_includes((ROOT / "templates" / m.group(1)).read_text(encoding="utf-8")))
        else:
            lines.append(line)
    return lines


UNROLL = re.compile(r"^(\s*)--@unroll$")
LOOP = re.compile(r"^(\s*)for k = (.+), (.+), (\S+) do$")
UNROLL_BY = 4


def unroll(lines: list[str]) -> list[str]:
    """Expands each `--@unroll` marker: the loop `for k = start, stop, step do ... end` on
    the next line becomes a loop doing UNROLL_BY iterations' bodies per pass (each in its
    own do-block, with k offset by multiples of step) and a loop over the remainder. The
    bodies run in the same order, so results are unchanged. Loop overhead dominates short
    loop bodies in Luau: unrolled axpy and dot run 3-4x faster."""
    out = []
    i = 0
    while i < len(lines):
        m = UNROLL.match(lines[i])
        if not m:
            out.append(lines[i])
            i += 1
            continue
        loop = LOOP.match(lines[i + 1])
        assert loop and loop.group(1) == m.group(1), f"--@unroll must precede a loop over k: {lines[i + 1]!r}"
        ind, start, stop, step = loop.groups()
        j = i + 2
        while lines[j] != ind + "end":
            j += 1
        body = lines[i + 2:j]
        out.append(f"{ind}do")
        out.append(f"{ind}\tlocal k_start, k_stop = {start}, {stop}")
        out.append(f"{ind}\tlocal k_split = k_start + ({step}) * (((k_stop - k_start) // ({step}) + 1) // {UNROLL_BY} * {UNROLL_BY})")
        out.append(f"{ind}\tfor k = k_start, k_split - 1, {UNROLL_BY} * ({step}) do")
        for t in range(UNROLL_BY):
            out.append(f"{ind}\t\tdo")
            offset = f"(k + {step} * {t})" if t else "k"
            out += ["\t\t" + re.sub(r"\bk\b", offset, line) for line in body]
            out.append(f"{ind}\t\tend")
        out.append(f"{ind}\tend")
        out.append(f"{ind}\tfor k = k_split, k_stop, {step} do")
        out += ["\t" + line for line in body]
        out.append(f"{ind}\tend")
        out.append(f"{ind}end")
        i = j + 1
    return out


OPTIONAL = "--@optional"


def prune(lines: list[str]) -> list[str]:
    """Drops each `--@optional` definition (a function up to its closing `end`, or a
    one-line local or type alias, with the comments above it) that nothing else in the
    module uses: the prelude's helpers are copied into every part, and most parts need only
    a few."""
    while True:
        blocks = []
        for i, line in enumerate(lines):
            if line != OPTIONAL:
                continue
            j = i + 1
            while lines[j].startswith("--") and not re.match(r"^--@(f32|f64|c32|c64) ", lines[j]):
                j += 1
            body = re.sub(r"^--@\w+ ?", "", lines[j])
            m = re.match(r"^(?:local (?:function )?|type )(\w+)", body)
            assert m, f"--@optional must precede a local or type definition: {lines[j]!r}"
            end = j
            if body.startswith("local function"):
                while re.sub(r"^--@\w+ ?", "", lines[end]) != "end":
                    end += 1
            blocks.append((i, end, m.group(1)))
        drop = None
        for i, end, name in blocks:
            # uses in code: not in comments, not fields (buffer.create), not other locals of
            # the same name
            used = False
            for l in lines[:i] + lines[end + 1:]:
                code = re.sub(r'"[^"]*"', '""', re.sub(r"--.*$", "", l))
                if re.search(rf"(?<![\w.]){name}\b", code) and not re.match(rf"^\s*(local|for)\s+[\w\s,]*\b{name}\b\s*[,=:]", code):
                    used = True
                    break
            if not used:
                drop = (i, end)
                break
        if drop is None:
            return [l for l in lines if l != OPTIONAL]
        lines = lines[: drop[0]] + lines[drop[1] + 1:]


def render(template: str, subs: dict) -> str:
    lines = []
    for line in expand_includes(template):
        m = MARKER.match(line)
        if m:
            if m.group(1) != subs.get("TAG"):
                continue
            line = m.group(2)
        lines.append(line)
    text = "\n".join(unroll(prune(lines))) + "\n"
    # (pruning leaves the blank lines around what it dropped)
    text = re.sub(r"\n{3,}", "\n\n", text)

    def sub(m):
        key = m.group(1)
        if key not in subs:
            raise KeyError(f"no value for @{key}@")
        return subs[key]

    return PLACEHOLDER.sub(sub, text)


def main() -> int:
    check = "--check" in sys.argv[1:]
    sys.path.insert(0, str(ROOT / "tools"))
    # No bytecode cache: an edit within the same second as the cache can go unseen.
    sys.dont_write_bytecode = True
    import gen_kernels
    import gen_sparse_kernels
    import gen_docs

    written = gen_kernels.main(check) + gen_sparse_kernels.main(check)
    stale = [f"templates/kernels/{name}" for name in written] if check else []
    for name in [] if check else written:
        print(f"wrote templates/kernels/{name}")
    for template, target, subs in TARGETS:
        text = render((ROOT / "templates" / template).read_text(encoding="utf-8"), subs)
        path = ROOT / "src" / target
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            continue
        if check:
            stale.append(target)
        else:
            path.write_text(text, encoding="utf-8", newline="\n")
            print(f"wrote src/{target}")
    # The API reference, from the doc comments of the generated modules.
    docs = gen_docs.main(check)
    stale += docs if check else []
    for name in [] if check else docs:
        print(f"wrote {name}")
    if stale:
        print("out of date (run python tools/generate.py): " + ", ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
