"""Writes the documentation in docs/ as pages of the GitHub wiki.

docs/ stays the source (versioned with the code; docs/reference/ is generated by
generate.py); the wiki is a copy for reading. Each page is named by its title, the
reference pages with " reference" appended, since several share a title with a guide.
Links between pages are rewritten to wiki links; links to other files of the repository
point to them on GitHub. docs/README.md becomes Home, and _Sidebar.md lists every page.

Usage: python tools/publish_wiki.py <wiki checkout>
  then commit and push in the checkout (git clone https://github.com/<owner>/citrate.wiki.git).
Every .md page in the checkout is replaced.
"""

import posixpath
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"
REPO = "https://github.com/aidan-epperly/citrate/blob/main"
LINK = re.compile(r"\]\(([^)\s]+)\)")


def title(path: Path) -> str:
    first = path.read_text(encoding="utf-8").splitlines()[0]
    assert first.startswith("# "), f"{path} does not start with a title"
    return first[2:].strip()


def pages() -> dict[str, str]:
    """docs-relative path -> wiki page name."""
    names = {"README.md": "Home"}
    for path in sorted(DOCS.glob("*.md")):
        if path.name != "README.md":
            names[path.name] = title(path)
    for path in sorted((DOCS / "reference").glob("*.md")):
        rel = f"reference/{path.name}"
        names[rel] = "API reference" if path.name == "README.md" else f"{title(path)} reference"
    assert len(set(names.values())) == len(names), "two pages have the same name"
    return names


def slug(name: str) -> str:
    """The wiki's file and URL name of a page."""
    return name.replace(" ", "-")


def convert(rel: str, names: dict[str, str]) -> str:
    text = (DOCS / rel).read_text(encoding="utf-8")
    here = posixpath.dirname(rel)

    def link(m: re.Match) -> str:
        target = m.group(1)
        if re.match(r"^[a-z]+:", target) or target.startswith("#"):
            return m.group(0)
        path, _, anchor = target.partition("#")
        in_repo = posixpath.normpath(posixpath.join("docs", here, path))
        assert not in_repo.startswith(".."), f"{rel}: link outside the repository: {target}"
        page = names.get(in_repo.removeprefix("docs/"))
        url = slug(page) if page and in_repo.startswith("docs/") else f"{REPO}/{in_repo}"
        assert (ROOT / in_repo).exists(), f"{rel}: broken link: {target}"
        return f"]({url}{'#' + anchor if anchor else ''})"

    text = LINK.sub(link, text)
    if rel == "README.md":
        # The wiki shows the page name as its title.
        text = text.split("\n", 1)[1].lstrip("\n")
    source = f"{REPO}/docs/{rel}"
    return text.rstrip("\n") + f"\n\n---\n\n_Generated from [docs/{rel}]({source}); edit it there._\n"


def listed(index: str, prefix: str, names: dict[str, str]) -> list[str]:
    """The pages under prefix, in the order the index page links them, then any others."""
    order = []
    for target in LINK.findall((DOCS / index).read_text(encoding="utf-8")):
        rel = posixpath.normpath(posixpath.join(posixpath.dirname(index), target.partition("#")[0]))
        if rel in names and rel != index and rel.startswith(prefix) and "/" not in rel[len(prefix):] and rel not in order:
            order.append(rel)
    rest = [rel for rel in names if rel.startswith(prefix) and "/" not in rel[len(prefix):]]
    return order + [rel for rel in rest if rel not in order and not rel.endswith("README.md")]


def sidebar(names: dict[str, str]) -> str:
    lines = ["**[Home](Home)**", "", "**Guides**", ""]
    lines += [f"- [{names[rel]}]({slug(names[rel])})" for rel in listed("README.md", "", names)]
    lines += ["", "**[API reference](API-reference)**", ""]
    for rel in listed("reference/README.md", "reference/", names):
        lines.append(f"- [{names[rel].removesuffix(' reference')}]({slug(names[rel])})")
    return "\n".join(lines) + "\n"


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__)
        return 2
    out = Path(sys.argv[1])
    assert (out / ".git").exists(), f"{out} is not a git checkout of the wiki"
    for old in out.glob("*.md"):
        old.unlink()
    names = pages()
    for rel, name in names.items():
        (out / f"{slug(name)}.md").write_text(convert(rel, names), encoding="utf-8", newline="\n")
    (out / "_Sidebar.md").write_text(sidebar(names), encoding="utf-8", newline="\n")
    print(f"wrote {len(names)} pages and _Sidebar.md to {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
