"""Generate the sparse product kernels templates/sparse_real.luau.in and sparse_complex.luau.in.

Cost model (measured, bench/sparse.luau; the same in Roblox Studio): in native Luau a
sparse product is not limited by memory bandwidth but by instructions, mostly a fixed cost
per loop iteration (about 1.6 ns) plus a smaller one per buffer read (about 0.25 ns) and a
few ns per row or column. A kernel that handles E stored entries per iteration with R reads
costs about (1.6 + 0.25 R) / E ns per entry, so:
- the scalar kernels unroll by 4 (by 8 gains nothing once the remainder loop is counted);
- the block kernels handle a b by b block per iteration: one index read serves b^2 entries
  and each x value read serves b rows (3 by 3: 0.53 ns per entry against 2.4 for the plain
  loop and 1.2 unrolled).
Sums run in double precision: in locals, or for scatters in an f64 accumulator buffer.

Usage: python tools/gen_sparse_kernels.py (generate.py runs it).
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
U = 4
BLOCKS = (2, 3, 4)

HEADER = """	-- Sparse product kernels (generated by tools/gen_sparse_kernels.py; do not edit).
	--   spk.gather(o, S, x{conj})  o := S^{sadj} x (a gather down the columns of S)
	--   spk.scatter(acc, S, x)  acc[row] += S[row, j] x[j] (acc: f64, {per} per row, zeroed)
	--   spk.block[b].mv(o, B, x)   o := B x for a block sparse B with b by b blocks
	--   spk.block[b].mvt(acc, B, x)  acc += B^{badj} x (acc as for scatter)
	--   spk.block[b].jacobi(o, inv, r, nb)  o := blockdiag(inv) r for nb f64 inverse blocks
	-- Unrolled by {U}; blocks are handled one per iteration (see the cost model in the
	-- generator).
	local spk: any = {{ block = {{}} }}
	do
"""


def real_gather():
    L = ["\t\tfunction spk.gather(o: buffer, S: Sparse, x: buffer)",
         "\t\t\tlocal colptr, rowind, vals = S.colptr, S.rowind, S.values",
         "\t\t\tlocal p0 = buffer.readu32(colptr, 0)",
         "\t\t\tfor j = 0, S.cols - 1 do",
         "\t\t\t\tlocal p1 = buffer.readu32(colptr, 4 * j + 4)",
         f"\t\t\t\tlocal pu = p1 - (p1 - p0) % {U}",
         "\t\t\t\tlocal s0, s1 = 0, 0",
         f"\t\t\t\tfor p = p0, pu - 1, {U} do",
         "\t\t\t\t\tlocal v, c = @W@ * p, 4 * p"]
    terms = [f"@READ@(vals, v + @W@ * {t}) * @READ@(x, @W@ * buffer.readu32(rowind, c + {4 * t}))" for t in range(U)]
    half = U // 2
    L.append("\t\t\t\t\ts0 += " + " + ".join(terms[:half]))
    L.append("\t\t\t\t\ts1 += " + " + ".join(terms[half:]))
    L += ["\t\t\t\tend",
          "\t\t\t\tfor p = pu, p1 - 1 do",
          "\t\t\t\t\ts0 += @READ@(vals, @W@ * p) * @READ@(x, @W@ * buffer.readu32(rowind, 4 * p))",
          "\t\t\t\tend",
          "\t\t\t\t@WRITE@(o, @W@ * j, s0 + s1)",
          "\t\t\t\tp0 = p1",
          "\t\t\tend",
          "\t\tend"]
    return "\n".join(L)


def real_scatter():
    L = ["\t\tfunction spk.scatter(acc: buffer, S: Sparse, x: buffer)",
         "\t\t\tlocal colptr, rowind, vals = S.colptr, S.rowind, S.values",
         "\t\t\tlocal p0 = buffer.readu32(colptr, 0)",
         "\t\t\tfor j = 0, S.cols - 1 do",
         "\t\t\t\tlocal p1 = buffer.readu32(colptr, 4 * j + 4)",
         "\t\t\t\tlocal xj = @READ@(x, @W@ * j)",
         "\t\t\t\tif xj ~= 0 then",
         f"\t\t\t\t\tlocal pu = p1 - (p1 - p0) % {U}",
         f"\t\t\t\t\tfor p = p0, pu - 1, {U} do",
         "\t\t\t\t\t\tlocal v, c = @W@ * p, 4 * p",
         "\t\t\t\t\t\tlocal " + ", ".join(f"r{t}" for t in range(U)) + " = " + ", ".join(f"8 * buffer.readu32(rowind, c + {4 * t})" for t in range(U))]
    for t in range(U):
        L.append(f"\t\t\t\t\t\tbuffer.writef64(acc, r{t}, buffer.readf64(acc, r{t}) + @READ@(vals, v + @W@ * {t}) * xj)")
    L += ["\t\t\t\t\tend",
          "\t\t\t\t\tfor p = pu, p1 - 1 do",
          "\t\t\t\t\t\tlocal r = 8 * buffer.readu32(rowind, 4 * p)",
          "\t\t\t\t\t\tbuffer.writef64(acc, r, buffer.readf64(acc, r) + @READ@(vals, @W@ * p) * xj)",
          "\t\t\t\t\tend",
          "\t\t\t\tend",
          "\t\t\t\tp0 = p1",
          "\t\t\tend",
          "\t\tend"]
    return "\n".join(L)


def complex_gather():
    # sg = -1 conjugates the entries (S^H x); 1 gives S^T x.
    L = ["\t\tfunction spk.gather(o: buffer, S: Sparse, x: buffer, sg: number)",
         "\t\t\tlocal colptr, rowind, vals = S.colptr, S.rowind, S.values",
         "\t\t\tlocal p0 = buffer.readu32(colptr, 0)",
         "\t\t\tfor j = 0, S.cols - 1 do",
         "\t\t\t\tlocal p1 = buffer.readu32(colptr, 4 * j + 4)",
         f"\t\t\t\tlocal pu = p1 - (p1 - p0) % {U}",
         "\t\t\t\tlocal sr, si = 0, 0",
         f"\t\t\t\tfor p = p0, pu - 1, {U} do",
         "\t\t\t\t\tlocal v, c = @E@ * p, 4 * p"]
    for t in range(U):
        L.append(f"\t\t\t\t\tdo")
        L.append(f"\t\t\t\t\t\tlocal r = @E@ * buffer.readu32(rowind, c + {4 * t})")
        L.append(f"\t\t\t\t\t\tlocal ar, ai = @READ@(vals, v + @E@ * {t}), sg * @READ@(vals, v + @E@ * {t} + @W@)")
        L.append(f"\t\t\t\t\t\tlocal xr, xi = @READ@(x, r), @READ@(x, r + @W@)")
        L.append(f"\t\t\t\t\t\tsr += ar * xr - ai * xi")
        L.append(f"\t\t\t\t\t\tsi += ar * xi + ai * xr")
        L.append(f"\t\t\t\t\tend")
    L += ["\t\t\t\tend",
          "\t\t\t\tfor p = pu, p1 - 1 do",
          "\t\t\t\t\tlocal r = @E@ * buffer.readu32(rowind, 4 * p)",
          "\t\t\t\t\tlocal ar, ai = @READ@(vals, @E@ * p), sg * @READ@(vals, @E@ * p + @W@)",
          "\t\t\t\t\tlocal xr, xi = @READ@(x, r), @READ@(x, r + @W@)",
          "\t\t\t\t\tsr += ar * xr - ai * xi",
          "\t\t\t\t\tsi += ar * xi + ai * xr",
          "\t\t\t\tend",
          "\t\t\t\t@WRITE@(o, @E@ * j, sr)",
          "\t\t\t\t@WRITE@(o, @E@ * j + @W@, si)",
          "\t\t\t\tp0 = p1",
          "\t\t\tend",
          "\t\tend"]
    return "\n".join(L)


def complex_scatter():
    L = ["\t\tfunction spk.scatter(acc: buffer, S: Sparse, x: buffer)",
         "\t\t\tlocal colptr, rowind, vals = S.colptr, S.rowind, S.values",
         "\t\t\tlocal p0 = buffer.readu32(colptr, 0)",
         "\t\t\tfor j = 0, S.cols - 1 do",
         "\t\t\t\tlocal p1 = buffer.readu32(colptr, 4 * j + 4)",
         "\t\t\t\tlocal xr, xi = @READ@(x, @E@ * j), @READ@(x, @E@ * j + @W@)",
         "\t\t\t\tif xr ~= 0 or xi ~= 0 then",
         f"\t\t\t\t\tlocal pu = p1 - (p1 - p0) % {U}",
         f"\t\t\t\t\tfor p = p0, pu - 1, {U} do",
         "\t\t\t\t\t\tlocal v, c = @E@ * p, 4 * p"]
    for t in range(U):
        L.append(f"\t\t\t\t\t\tdo")
        L.append(f"\t\t\t\t\t\t\tlocal r = 16 * buffer.readu32(rowind, c + {4 * t})")
        L.append(f"\t\t\t\t\t\t\tlocal ar, ai = @READ@(vals, v + @E@ * {t}), @READ@(vals, v + @E@ * {t} + @W@)")
        L.append(f"\t\t\t\t\t\t\tbuffer.writef64(acc, r, buffer.readf64(acc, r) + (ar * xr - ai * xi))")
        L.append(f"\t\t\t\t\t\t\tbuffer.writef64(acc, r + 8, buffer.readf64(acc, r + 8) + (ar * xi + ai * xr))")
        L.append(f"\t\t\t\t\t\tend")
    L += ["\t\t\t\t\tend",
          "\t\t\t\t\tfor p = pu, p1 - 1 do",
          "\t\t\t\t\t\tlocal r = 16 * buffer.readu32(rowind, 4 * p)",
          "\t\t\t\t\t\tlocal ar, ai = @READ@(vals, @E@ * p), @READ@(vals, @E@ * p + @W@)",
          "\t\t\t\t\t\tbuffer.writef64(acc, r, buffer.readf64(acc, r) + (ar * xr - ai * xi))",
          "\t\t\t\t\t\tbuffer.writef64(acc, r + 8, buffer.readf64(acc, r + 8) + (ar * xi + ai * xr))",
          "\t\t\t\t\tend",
          "\t\t\t\tend",
          "\t\t\t\tp0 = p1",
          "\t\t\tend",
          "\t\tend"]
    return "\n".join(L)


def real_block(b):
    xs = ", ".join(f"x{k}" for k in range(b))
    L = [f"\t\tlocal function mv{b}(o: buffer, B: BlockSparse, x: buffer)",
         "\t\t\tlocal rowptr, colind, vals = B.rowptr, B.colind, B.values",
         "\t\t\tlocal p0 = buffer.readu32(rowptr, 0)",
         f"\t\t\tfor I = 0, B.rows // {b} - 1 do",
         "\t\t\t\tlocal p1 = buffer.readu32(rowptr, 4 * I + 4)",
         "\t\t\t\tlocal " + ", ".join(f"s{r}" for r in range(b)) + " = " + ", ".join("0" for _ in range(b)),
         "\t\t\t\tfor p = p0, p1 - 1 do",
         f"\t\t\t\t\tlocal c = @W@ * {b} * buffer.readu32(colind, 4 * p)",
         f"\t\t\t\t\tlocal {xs} = " + ", ".join(f"@READ@(x, c + @W@ * {k})" for k in range(b)),
         f"\t\t\t\t\tlocal v = @W@ * {b * b} * p"]
    for r in range(b):
        L.append(f"\t\t\t\t\ts{r} += " + " + ".join(f"@READ@(vals, v + @W@ * {k * b + r}) * x{k}" for k in range(b)))
    L += ["\t\t\t\tend", f"\t\t\t\tlocal w = @W@ * {b} * I"]
    L += [f"\t\t\t\t@WRITE@(o, w + @W@ * {r}, s{r})" for r in range(b)]
    L += ["\t\t\t\tp0 = p1", "\t\t\tend", "\t\tend", ""]
    # acc += B^T x: block (I, J) adds its transpose times x's block I to block J.
    L += [f"\t\tlocal function mvt{b}(acc: buffer, B: BlockSparse, x: buffer)",
          "\t\t\tlocal rowptr, colind, vals = B.rowptr, B.colind, B.values",
          "\t\t\tlocal p0 = buffer.readu32(rowptr, 0)",
          f"\t\t\tfor I = 0, B.rows // {b} - 1 do",
          "\t\t\t\tlocal p1 = buffer.readu32(rowptr, 4 * I + 4)",
          f"\t\t\t\tlocal xb = @W@ * {b} * I",
          f"\t\t\t\tlocal {xs} = " + ", ".join(f"@READ@(x, xb + @W@ * {k})" for k in range(b)),
          "\t\t\t\tfor p = p0, p1 - 1 do",
          f"\t\t\t\t\tlocal c = {8 * b} * buffer.readu32(colind, 4 * p)",
          f"\t\t\t\t\tlocal v = @W@ * {b * b} * p"]
    for k in range(b):
        off = f"c + {8 * k}" if k else "c"
        L.append(f"\t\t\t\t\tbuffer.writef64(acc, {off}, buffer.readf64(acc, {off}) + (" + " + ".join(f"@READ@(vals, v + @W@ * {k * b + r}) * x{r}" for r in range(b)) + "))")
    L += ["\t\t\t\tend", "\t\t\t\tp0 = p1", "\t\t\tend", "\t\tend", ""]
    # o := blockdiag(inv) r, inv holding nb f64 b by b blocks (column-major).
    L += [f"\t\tlocal function pj{b}(o: buffer, inv: buffer, r: buffer, nb: number)",
          "\t\t\tfor I = 0, nb - 1 do",
          f"\t\t\t\tlocal base, v = @W@ * {b} * I, {8 * b * b} * I",
          "\t\t\t\tlocal " + ", ".join(f"t{k}" for k in range(b)) + " = " + ", ".join(f"@READ@(r, base + @W@ * {k})" for k in range(b))]
    for i in range(b):
        L.append(f"\t\t\t\t@WRITE@(o, base + @W@ * {i}, " + " + ".join(f"buffer.readf64(inv, v + {8 * (k * b + i)}) * t{k}" for k in range(b)) + ")")
    L += ["\t\t\tend", "\t\tend", "",
          f"\t\tspk.block[{b}] = {{ mv = mv{b}, mvt = mvt{b}, jacobi = pj{b} }}"]
    return "\n".join(L)


def complex_block(b):
    xs = ", ".join(f"xr{k}, xi{k}" for k in range(b))
    xr = lambda base: ", ".join(f"@READ@(x, {base} + @E@ * {k}), @READ@(x, {base} + @E@ * {k} + @W@)" for k in range(b))
    L = [f"\t\tlocal function mv{b}(o: buffer, B: BlockSparse, x: buffer)",
         "\t\t\tlocal rowptr, colind, vals = B.rowptr, B.colind, B.values",
         "\t\t\tlocal p0 = buffer.readu32(rowptr, 0)",
         f"\t\t\tfor I = 0, B.rows // {b} - 1 do",
         "\t\t\t\tlocal p1 = buffer.readu32(rowptr, 4 * I + 4)",
         "\t\t\t\tlocal " + ", ".join(f"sr{r}, si{r}" for r in range(b)) + " = " + ", ".join("0, 0" for _ in range(b)),
         "\t\t\t\tfor p = p0, p1 - 1 do",
         f"\t\t\t\t\tlocal c = @E@ * {b} * buffer.readu32(colind, 4 * p)",
         f"\t\t\t\t\tlocal {xs} = {xr('c')}",
         f"\t\t\t\t\tlocal v = @E@ * {b * b} * p"]
    for r in range(b):
        for k in range(b):
            e = k * b + r
            L.append(f"\t\t\t\t\tdo local ar, ai = @READ@(vals, v + @E@ * {e}), @READ@(vals, v + @E@ * {e} + @W@); sr{r} += ar * xr{k} - ai * xi{k}; si{r} += ar * xi{k} + ai * xr{k} end")
    L += ["\t\t\t\tend", f"\t\t\t\tlocal w = @E@ * {b} * I"]
    for r in range(b):
        L.append(f"\t\t\t\t@WRITE@(o, w + @E@ * {r}, sr{r})")
        L.append(f"\t\t\t\t@WRITE@(o, w + @E@ * {r} + @W@, si{r})")
    L += ["\t\t\t\tp0 = p1", "\t\t\tend", "\t\tend", ""]
    # acc += B^H x: block (I, J) adds its conjugate transpose times x's block I to block J.
    L += [f"\t\tlocal function mvt{b}(acc: buffer, B: BlockSparse, x: buffer)",
          "\t\t\tlocal rowptr, colind, vals = B.rowptr, B.colind, B.values",
          "\t\t\tlocal p0 = buffer.readu32(rowptr, 0)",
          f"\t\t\tfor I = 0, B.rows // {b} - 1 do",
          "\t\t\t\tlocal p1 = buffer.readu32(rowptr, 4 * I + 4)",
          f"\t\t\t\tlocal xb = @E@ * {b} * I",
          f"\t\t\t\tlocal {xs} = {xr('xb')}",
          "\t\t\t\tfor p = p0, p1 - 1 do",
          f"\t\t\t\t\tlocal c = {16 * b} * buffer.readu32(colind, 4 * p)",
          f"\t\t\t\t\tlocal v = @E@ * {b * b} * p"]
    for k in range(b):
        L.append("\t\t\t\t\tdo")
        L.append("\t\t\t\t\t\tlocal ur, ui = 0, 0")
        for r in range(b):
            e = k * b + r
            # conj(a) x = (ar - i ai)(xr + i xi)
            L.append(f"\t\t\t\t\t\tdo local ar, ai = @READ@(vals, v + @E@ * {e}), @READ@(vals, v + @E@ * {e} + @W@); ur += ar * xr{r} + ai * xi{r}; ui += ar * xi{r} - ai * xr{r} end")
        off = f"c + {16 * k}" if k else "c"
        L.append(f"\t\t\t\t\t\tbuffer.writef64(acc, {off}, buffer.readf64(acc, {off}) + ur)")
        L.append(f"\t\t\t\t\t\tbuffer.writef64(acc, {off} + 8, buffer.readf64(acc, {off} + 8) + ui)")
        L.append("\t\t\t\t\tend")
    L += ["\t\t\t\tend", "\t\t\t\tp0 = p1", "\t\t\tend", "\t\tend", ""]
    # o := blockdiag(inv) r, inv holding nb b by b blocks of f64 (re, im) pairs, column-major.
    L += [f"\t\tlocal function pj{b}(o: buffer, inv: buffer, r: buffer, nb: number)",
          "\t\t\tfor I = 0, nb - 1 do",
          f"\t\t\t\tlocal base, v = @E@ * {b} * I, {16 * b * b} * I",
          "\t\t\t\tlocal " + ", ".join(f"tr{k}, ti{k}" for k in range(b)) + " = " + ", ".join(f"@READ@(r, base + @E@ * {k}), @READ@(r, base + @E@ * {k} + @W@)" for k in range(b))]
    for i in range(b):
        L.append("\t\t\t\tdo")
        L.append("\t\t\t\t\tlocal ur, ui = 0, 0")
        for k in range(b):
            e = 16 * (k * b + i)
            L.append(f"\t\t\t\t\tdo local ar, ai = buffer.readf64(inv, v + {e}), buffer.readf64(inv, v + {e + 8}); ur += ar * tr{k} - ai * ti{k}; ui += ar * ti{k} + ai * tr{k} end")
        L.append(f"\t\t\t\t\t@WRITE@(o, base + @E@ * {i}, ur)")
        L.append(f"\t\t\t\t\t@WRITE@(o, base + @E@ * {i} + @W@, ui)")
        L.append("\t\t\t\tend")
    L += ["\t\t\tend", "\t\tend", "",
          f"\t\tspk.block[{b}] = {{ mv = mv{b}, mvt = mvt{b}, jacobi = pj{b} }}"]
    return "\n".join(L)


def kernel_file(complex_):
    head = HEADER.format(conj=", sg" if complex_ else "",
                         sadj="H (sg = -1) or S^T (sg = 1)" if complex_ else "T", badj="H" if complex_ else "T",
                         per="re, im" if complex_ else "one", U=U)
    parts = [head.rstrip("\n")]
    parts.append(complex_gather() if complex_ else real_gather())
    parts.append("")
    parts.append(complex_scatter() if complex_ else real_scatter())
    for b in BLOCKS:
        parts.append("")
        parts.append(complex_block(b) if complex_ else real_block(b))
    parts.append("\tend")
    return "\n".join(parts) + "\n"


def outputs() -> dict:
    return {"sparse_real.luau.in": kernel_file(False), "sparse_complex.luau.in": kernel_file(True)}


def main(check: bool = False) -> list:
    stale = []
    for name, text in outputs().items():
        path = ROOT / "templates" / name
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != text:
            stale.append(name)
            if not check:
                path.write_text(text, encoding="utf-8", newline="\n")
    return stale


if __name__ == "__main__":
    import sys

    print(main("--check" in sys.argv[1:]) or "sparse kernels up to date")
